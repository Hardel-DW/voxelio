import type { ModMetadata } from "@/types";
import { DEFAULT_MOD_METADATA, ModPlatforms } from "@/types";

type ForgePlatform = typeof ModPlatforms.FORGE | typeof ModPlatforms.NEOFORGE;

// NeoForge 26.1 reads logoFile, later versions read iconFile and only warn about logoFile.
const LOADER_CONFIG = {
	[ModPlatforms.FORGE]: { loader: "lowcodefml", version: "[40,)", iconKeys: ["logoFile"], updateQuery: "" },
	[ModPlatforms.NEOFORGE]: { loader: "javafml", version: "[1,)", iconKeys: ["logoFile", "iconFile"], updateQuery: "?neoforge=only" }
} as const;

const TOML_ESCAPES: Record<string, string> = { "\\": "\\\\", '"': '\\"', "\b": "\\b", "\t": "\\t", "\n": "\\n", "\f": "\\f", "\r": "\\r" };

/**
 * Writes a TOML basic string, escaping every character TOML forbids raw in it.
 */
export const tomlString = (value: string): string =>
	// biome-ignore lint/suspicious/noControlCharactersInRegex: these are exactly the characters TOML forbids raw
	`"${value.replace(/[\\"\u0000-\u001f\u007f]/g, (char) => TOML_ESCAPES[char] ?? `\\u${char.charCodeAt(0).toString(16).padStart(4, "0")}`)}"`;

const buildModEntry = (mod: ModMetadata, platform: ForgePlatform): string => {
	const config = LOADER_CONFIG[platform];
	const fields = new Map([
		["modId", mod.id],
		["version", mod.version],
		["displayName", mod.name],
		["description", mod.description],
		["credits", "Generated by DatapackConverter"]
	]);

	if (mod.icon) for (const key of config.iconKeys) fields.set(key, mod.icon);
	if (mod.authors.length) fields.set("authors", mod.authors.join(", "));

	if (mod.homepage && mod.homepage !== DEFAULT_MOD_METADATA.homepage) {
		fields.set("updateJSONURL", `${mod.homepage}/updates.json${config.updateQuery}`);
		fields.set("displayURL", mod.homepage);
	}

	return `\t{ ${[...fields].map(([k, v]) => `${k} = ${tomlString(v)}`).join(", ")} }`;
};

/**
 * Generates TOML content for Forge (mods.toml) or NeoForge (neoforge.mods.toml)
 * @param metadata - Common mod metadata
 * @param platform - Target loader
 * @returns Formatted TOML content
 */
export function generateForgeMods(metadata: ModMetadata, platform: ForgePlatform): string {
	const config = LOADER_CONFIG[platform];
	const fields = new Map<string, string | boolean>([
		["modLoader", config.loader],
		["loaderVersion", config.version],
		["license", "LicenseRef-Datapack"],
		["showAsResourcePack", false]
	]);

	if (metadata.issues && metadata.issues !== DEFAULT_MOD_METADATA.issues) {
		fields.set("issueTrackerURL", metadata.issues);
	}

	const lines = [...fields].map(([key, value]) => (typeof value === "boolean" ? `${key} = ${value}` : `${key} = ${tomlString(value)}`));
	return [...lines, "mods = [", buildModEntry(metadata, platform), "]"].join("\n");
}
